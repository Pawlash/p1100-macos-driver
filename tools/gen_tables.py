#!/usr/bin/env python3
"""Generate build/screens.h from the two halftone screens pulled out of HP's driver.

  gen_tables.py HPDIR OUT.h

HPDIR is what tools/fetch_hp_files.sh wrote (sdtahs10.bin, sdtahr10.bin). These come from
HP's own driver, so they are not part of the repository and never get committed.
"""
import os
import sys


def carray(name, data, ctype="uint8_t", per_line=24):
    out = ["static const %s %s[%d] = {" % (ctype, name, len(data))]
    for i in range(0, len(data), per_line):
        out.append("    " + ",".join(str(v) for v in data[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main(tdir, dst):
    parts = ["/* Generated by tools/gen_tables.py from HP's driver - do not commit. */",
             "#pragma once", "#include <stdint.h>", ""]
    parts.append("/* 12x12 halftone screens, 2 bits per pixel, 256 levels x 12 rows x 4 bytes.\n"
                 " * sdtahs10 is used for 'FastRes 600' (600x400 label), sdtahr10 for 'FastRes 1200'. */")
    for n in ("sdtahs10", "sdtahr10"):
        parts.append(carray("screen_" + n[5:], open(os.path.join(tdir, n + ".bin"), "rb").read()))
        parts.append("")
    open(dst, "w").write("\n".join(parts) + "\n")


if __name__ == "__main__":
    main(sys.argv[1], sys.argv[2])
